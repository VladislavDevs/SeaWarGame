package battleship.model;

/**
 * Состояния клетки игрового поля согласно заданию:
 *  EMPTY — закрытая пустая клетка
 *  SHIP  — закрытая клетка с кораблём
 *  MISS  — пустая клетка, по которой был прилёт
 *  HIT   — клетка с кораблём, по которой был прилёт
 */
public enum CellState {
    EMPTY,
    SHIP,
    MISS,
    HIT
}